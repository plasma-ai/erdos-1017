def checker_coefficients():
    """Run the checker; return its Bernstein coefficients, in row-major order."""
    source = CHECKER.read_bytes()
    if hashlib.sha256(source).hexdigest() != CHECKER_SHA256:
        raise SystemExit(f'error: {CHECKER} is not the pinned checker')
    namespace = {'__name__': '__hard_corner_checker__'}
    captured = {}

    def recording(report):
        def record(name, polynomial, degree, minimum):
            count = report(name, polynomial, degree, minimum)
            box = namespace['bd'](polynomial, Fraction(1, 4), Fraction(2, 5), degree)
            captured[name] = [box[index] for index in product(*(range(d + 1) for d in degree))]
            return count
        return record

    printed = io.StringIO()
    with contextlib.redirect_stdout(printed):
        for statement in ast.parse(source, filename=str(CHECKER)).body:
            code = compile(ast.Module([statement], type_ignores=[]), str(CHECKER), 'exec')
            exec(code, namespace)
            if isinstance(statement, ast.FunctionDef) and statement.name == 'report':
                namespace['report'] = recording(namespace['report'])
    lines = printed.getvalue().splitlines()
    if lines[-1:] != ['ALL 11104 EXACT BERNSTEIN COEFFICIENTS POSITIVE']:
        raise SystemExit('error: the checker did not finish')
    for name, values in captured.items():
        digest = hashlib.sha256((' '.join(map(str, values)) + '\n').encode()).hexdigest()
        if f'{name} coefficient_sha256 {digest}' not in lines or COEFFICIENT_SHA256[name] != digest:
            raise SystemExit(f'error: {name}: coefficient digest mismatch')
    return captured


def scaled(values):
    """The least common denominator and the positive integers it gives."""
    denominator = lcm(*(value.denominator for value in values))
    integers = [int(value * denominator) for value in values]
    if min(integers) < 1:
        raise SystemExit('error: a coefficient is not positive')
    return denominator, integers


def power_stages(integers, degrees):
    """Stage s: the coefficients with the last s coordinates in the power basis."""
    stages = [dict(zip(product(*(range(d + 1) for d in degrees)), integers))]
    for step in range(1, len(degrees) + 1):
        axis = len(degrees) - step
        n = degrees[axis]
        converted = {}
        for index, value in stages[-1].items():
            b = index[axis]
            for j in range(b, n + 1):
                target = index[:axis] + (j,) + index[axis + 1:]
                converted[target] = (converted.get(target, 0)
                                     + value * comb(n, b) * comb(n - b, j - b) * (-1) ** (j - b))
        stages.append({index: value for index, value in converted.items() if value})
    return stages


