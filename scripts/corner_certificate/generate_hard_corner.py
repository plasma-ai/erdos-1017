#!/usr/bin/env python3
"""Generate the hard-sector corner certificate modules.

Input: `hard.py` in this directory, the exact checker of the hard sector; this
script checks its SHA-256 digest before running it. The checker expands four
polynomials in the Bernstein basis of their parameter boxes and asserts that
all 11,104 coefficients are positive rationals: `DJ_GUARD` (24),
`DUST_J_DERIVATIVE` (1,600), `DUST_J_LO` (3,600) and `Q_EQUALS_E` (5,880).
This script runs the checker, keeps the coefficients it computes, and compares
their SHA-256 digests with the ones the checker prints and with the recorded
ones below.

Output: the 32 modules `EmptySatCornerHard*.lean` of
`Erdos1017/Certificates/EmptySatCorner/`, written to the output directory
(default `.lake/hard-corner-certificate/`), never into the library. Each module
begins with a docstring that ends with "Generated by
`scripts/corner_certificate/generate_hard_corner.py`; do not edit by hand."

Each polynomial's coefficients are scaled by their least common denominator
to positive integers `N` and stored as `N - 1` in a `…Pred` table of natural
numbers (`guard_chartPred`, `derivativePred`, `lowerPred`, `momentPred`).
`…Stage s` holds the polynomial with the last `s` coordinates converted
exactly to the power basis, in Horner form. Lean proves every stage, one row
at a time, equal to a Bernstein evaluation of the stage before, so each stage
is at least 1 on the unit cube. The chart theorems prove the last stage equal
to the denominator times the Lean formula (`guard`, `clearedDerivative`,
`homogeneousZero`, `clearedMomentEndpoint`) on the box, so a wrong
coefficient fails to check. The script only chooses the literals and the
module layout; Lean checks every emitted statement. The hand-written
declarations (the score formulas, the interval reduction, the interpolation
lemmas of the chart identities) are kept verbatim at the end of this file;
the script inserts the denominators into them.

Module layout, rows grouped so that every module stays small:

- `Core`: the definitions, the guard chart, and every `Pred` and `Stage` table;
- `Derivative`: all derivative stages and `derivative_chart`;
- `Lower0`-`Lower3`, `LowerFirst`-`LowerFourth`, `LowerIdentity`, `Lower`:
  the lower-endpoint stages, by first coordinate, and `lower_chart`;
- `Moment0`-`Moment3`, `MomentFirst`, `MomentSecond0`-`MomentSecond3`,
  `MomentSecond`-`MomentFifth`, `MomentIdentitySlices0`-`3`,
  `MomentIdentity`, `Moment`: the moment-endpoint stages and `moment_chart`;
- `Certificates`: the statements on the real hard-sector enclosure.

Run from the repository root with Python 3.9 or later (standard library only):

    python3 scripts/corner_certificate/generate_hard_corner.py [output-directory]
    python3 scripts/corner_certificate/generate_hard_corner.py --check

With `--check` the script writes nothing and compares each generated module
with the library module of the same name, byte for byte.
"""

