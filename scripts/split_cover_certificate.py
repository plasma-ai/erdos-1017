#!/usr/bin/env python3
"""Split the large-atom middle-E2 cover into its piece and root modules.

Input: the cover shards that `MiddleE2LargeUniversalCertificateCoverGen.lean`
writes, by default to `.lake/cover-shards/` (another directory with
`--shards`). Their declarations `t0, t1, …` form one binary tree in
post-order: a leaf `cover d B = true` is closed by `decide +kernel`, and an
internal node combines its two halves with `cover_of_split`. The last
declaration closes `IBox.root` at depth 80.

Output: the 149 modules of `Erdos1017/Certificates/MiddleE2LargeUniversal/`
below, written to the output directory (default `.lake/cover-certificate/`),
never into the library.

- `MiddleE2LargeUniversalCertificatePiece000.lean`, … : every maximal subtree
  with at most `LEAVES` leaves, in tree order. Each piece imports only
  `MiddleE2LargeUniversalCertificateCover`, so the pieces build independently.
- `MiddleE2LargeUniversalCertificateRoot.lean`: the internal nodes above the
  pieces and `cover_root : cover 80 IBox.root = true`.

Each module begins with a docstring that ends with "Generated by
`scripts/split_cover_certificate.py` ...; do not edit by hand."

The script fails unless the declarations form one tree and every
`cover_of_split` refers to an earlier declaration. Lean checks every emitted
statement; the script only decides where each declaration goes. Run from the
repository root with Python 3 (standard library only):

    python3 scripts/split_cover_certificate.py [--shards DIR] [output-directory]
    python3 scripts/split_cover_certificate.py [--shards DIR] --check

With `--check` the script writes nothing and compares each generated module
with the library module of the same name, byte for byte.
"""

import re
import sys
from pathlib import Path

LEAVES = 150
PREFIX = 'Erdos1017.Certificates.MiddleE2LargeUniversal.'
NAMESPACE = 'Erdos1017.MiddleE2LargeUniversal.FixedPoint'
LIBRARY = Path('Erdos1017/Certificates/MiddleE2LargeUniversal')
DEFAULT_SHARDS = Path('.lake/cover-shards')
DEFAULT_OUTPUT = Path('.lake/cover-certificate')
GENERATOR = 'scripts/MiddleE2LargeUniversalCertificateCoverGen.lean'
DECLARATION = re.compile(
    r'^theorem t(\d+) : cover \d+ \(IBox\.mk[ \d]+\) = true :=(?: by decide \+kernel\n'
    r'|\n  cover_of_split t(\d+) t(\d+)\n)', re.M)
TOKEN = re.compile(r'`[^`]*`\S*|\S+')


def wrap(text, width=80):
    """Wrap a paragraph at `width` columns without breaking a backtick span."""
    lines, line = [], ''
    for token in TOKEN.findall(text):
        if line and len(line) + 1 + len(token) > width:
            lines.append(line)
            line = token
        else:
            line = f'{line} {token}' if line else token
    return '\n'.join(lines + [line] if line else lines)


def docstring(title, description):
    return (f'/-!\n# {title}\n\n{wrap(description)}\n\n'
            + wrap(f'Generated by `scripts/split_cover_certificate.py` from the shards of '
                   f'`{GENERATOR}`; do not edit by hand.') + '\n-/\n\n')


def read_declarations(directory):
    shards = sorted(directory.glob('MiddleE2LargeUniversalCertificateCoverShard*.lean'),
                    key=lambda path: int(re.search(r'Shard(\d+)', path.name).group(1)))
    if not shards:
        raise SystemExit(f'error: no cover shards in {directory}')
    texts, children = [], []
    for shard in shards:
        for match in DECLARATION.finditer(shard.read_text(encoding='utf-8')):
            index = int(match.group(1))
            if index != len(texts):
                raise SystemExit(f'error: {shard.name}: expected t{len(texts)}, found t{index}')
            pair = match.group(2) and (int(match.group(2)), int(match.group(3)))
            if pair and not max(pair) < index:
                raise SystemExit(f'error: t{index} refers to a later declaration')
            texts.append(match.group(0) + '\n')
            children.append(pair)
    return texts, children


def leaf_counts(children):
    counts = []
    for pair in children:
        counts.append(1 if pair is None else counts[pair[0]] + counts[pair[1]])
    return counts


def split(children, counts):
    """Pieces as subtree roots, and internal root nodes, both in tree order."""
    pieces, internal, stack = [], [], [len(children) - 1]
    while stack:
        node = stack.pop()
        if counts[node] <= LEAVES:
            pieces.append(node)
        else:
            internal.append(node)
            left, right = children[node]
            stack += [right, left]
    return sorted(pieces), sorted(internal)


def subtree(children, node):
    nodes, stack = [], [node]
    while stack:
        current = stack.pop()
        nodes.append(current)
        if children[current]:
            stack += children[current]
    return sorted(nodes)


def section(declarations):
    return ('@[expose] public section\n\n'
            f'namespace {NAMESPACE}.Cov\n\n'
            f'open {NAMESPACE}\n\n'
            + ''.join(declarations)
            + f'end {NAMESPACE}.Cov\n')


def modules(directory):
    """File name -> text of the 148 pieces and the root, in memory."""
    texts, children = read_declarations(directory)
    counts = leaf_counts(children)
    pieces, internal = split(children, counts)
    covered = sorted(i for p in pieces for i in subtree(children, p)) + internal
    if sorted(covered) != list(range(len(texts))):
        raise SystemExit('error: the declarations do not form one tree')
    width = 3
    out = {}
    for number, node in enumerate(pieces):
        nodes = subtree(children, node)
        leaves = sum(1 for i in nodes if children[i] is None)
        doc = docstring(
            f'Middle-E2 large-atom cover, piece {number:0{width}d}',
            f'The subtree of the fixed-point cover below `t{node}`: the declarations '
            f'`t{nodes[0]}` to `t{node}`, with {leaves} leaf boxes closed by '
            '`decide +kernel` and the other boxes by `cover_of_split`.')
        out[f'MiddleE2LargeUniversalCertificatePiece{number:0{width}d}.lean'] = (
            'module\n\n'
            f'public import {PREFIX}MiddleE2LargeUniversalCertificateCover\n\n'
            + doc + section(texts[i] for i in nodes))
    imports = ''.join(f'public import {PREFIX}MiddleE2LargeUniversalCertificatePiece{n:0{width}d}\n'
                      for n in range(len(pieces)))
    doc = docstring(
        'Middle-E2 large-atom cover, root',
        f'The {len(internal)} boxes above the {len(pieces)} pieces, each closed by '
        '`cover_of_split`, and `cover_root : cover 80 IBox.root = true`.')
    out['MiddleE2LargeUniversalCertificateRoot.lean'] = (
        'module\n\n' + imports + '\n' + doc
        + section(texts[i] for i in internal)
        + f'\nnamespace {NAMESPACE}\n\n'
        '/-- The finite fixed-point cover of the root box, assembled from its checked pieces. -/\n'
        f'theorem cover_root : cover 80 IBox.root = true := Cov.t{len(texts) - 1}\n\n'
        f'end {NAMESPACE}\n')
    print(f'{len(texts)} declarations: {len(pieces)} pieces, {len(internal)} root nodes')
    return out


def main():
    arguments = sys.argv[1:]
    check = '--check' in arguments
    arguments = [a for a in arguments if a != '--check']
    shards = DEFAULT_SHARDS
    if '--shards' in arguments:
        i = arguments.index('--shards')
        if i + 1 >= len(arguments):
            raise SystemExit('error: --shards needs a directory')
        shards = Path(arguments[i + 1])
        del arguments[i:i + 2]
    if len(arguments) > (0 if check else 1):
        raise SystemExit('usage: split_cover_certificate.py [--shards DIR] '
                         '[--check | output-directory]')
    generated = modules(shards)
    if check:
        differing = [name for name, text in sorted(generated.items())
                     if not (LIBRARY / name).is_file()
                     or (LIBRARY / name).read_text(encoding='utf-8') != text]
        library = {path.name for path in
                   LIBRARY.glob('MiddleE2LargeUniversalCertificatePiece*.lean')}
        extra = sorted(library - set(generated))
        for name in differing:
            print(f'differs: {LIBRARY / name}')
        for name in extra:
            print(f'not generated: {LIBRARY / name}')
        print(f'{len(generated) - len(differing)} of {len(generated)} modules identical')
        sys.exit(1 if differing or extra else 0)
    output = Path(arguments[0]) if arguments else DEFAULT_OUTPUT
    output.mkdir(parents=True, exist_ok=True)
    for name, text in generated.items():
        (output / name).write_text(text, encoding='utf-8')
    print(f'wrote {len(generated)} modules to {output}')


if __name__ == '__main__':
    main()
